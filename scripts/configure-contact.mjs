import { writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

export function productionContactConfig(value) {
  if (!value?.trim()) {
    return { apiBaseUrl: '' };
  }
  let url;
  try { url = new URL(value.trim()); }
  catch { throw new Error('CONTACT_API_URL must be a valid HTTPS origin.'); }
  if (url.protocol !== 'https:' || url.username || url.password || url.search || url.hash
      || url.pathname !== '/' || !url.hostname.includes('.') || url.hostname.endsWith('.localhost')
      || url.hostname === 'localhost' || url.hostname === '127.0.0.1' || url.hostname === '0.0.0.0') {
    throw new Error('CONTACT_API_URL must be a public HTTPS origin, with no credentials, path, query, or fragment. Do not include /api/contact.');
  }
  return { apiBaseUrl: url.origin };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const config = productionContactConfig(process.env.CONTACT_API_URL);
    await writeFile(new URL('../src/environments/environment.production.ts', import.meta.url),
      '// Generated by scripts/configure-contact.mjs. Public URL only; never add secrets.\n'
      + `export const environment = ${JSON.stringify(config)};\n`);
    console.log(config.apiBaseUrl ? 'Production contact API configured.' : 'Building portfolio with contact submissions unavailable until CONTACT_API_URL is set.');
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
